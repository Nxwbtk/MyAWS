// Generates src/app/one-theme.css: the AWS Console "one theme" token values
// (scripts/one-theme/*.txt) mapped onto the hashed custom properties used by
// the installed @cloudscape-design/components version.
//
//   node scripts/generate-one-theme.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const require = createRequire(join(root, "package.json"))
const componentsDir = dirname(require.resolve("@cloudscape-design/components/package.json"))
const baseCss = readFileSync(join(componentsDir, "internal/base-theme/styles.scoped.css"), "utf8")

// --color-text-body-default-abc123 -> color-text-body-default
const hashed = new Map()
for (const [, name] of baseCss.matchAll(/--([a-z0-9-]+?-[a-z0-9]{6}):/g)) {
  const base = name.replace(/-[a-z0-9]{6}$/, "")
  if (!hashed.has(base)) hashed.set(base, name)
}

function read(file) {
  return readFileSync(join(root, "scripts/one-theme", file), "utf8")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const index = line.indexOf(":")
      return [line.slice(0, index), line.slice(index + 1)]
    })
}

const resolveName = (name) => hashed.get(name) ?? name
let unmatched = 0

function declarations(entries) {
  return entries
    .map(([name, value]) => {
      if (!hashed.has(name) && !/^color-(primary|neutral|warning|info|error|success|grey)-/.test(name)) unmatched++
      const mapped = value.replace(/var\(--([a-z0-9-]+)\)/g, (_, ref) => `var(--${resolveName(ref)})`)
      return `  --${resolveName(name)}: ${mapped};`
    })
    .join("\n")
}

const palette = [
  ["color-white", "#ffffff"],
  ["color-black", "#000000"],
  ["color-transparent", "transparent"],
].filter(([name]) => !hashed.has(name))

const css = `/* Generated by scripts/generate-one-theme.mjs. Do not edit by hand. */
/* AWS Console "one theme" tokens mapped to @cloudscape-design/components. */

body {
${declarations([...palette, ...read("light.txt")])}
}

body.awsui-dark-mode,
.awsui-dark-mode {
${declarations(read("dark.txt"))}
}
`

writeFileSync(join(root, "src/app/one-theme.css"), css)
console.log(`Wrote src/app/one-theme.css (${hashed.size} Cloudscape tokens, ${unmatched} theme tokens without a match).`)
